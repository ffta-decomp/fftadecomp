"""Explicit, source-pinned optional build extensions; no localization policy."""
import copy
import hashlib
import json
from pathlib import Path


def digest(data):
    return hashlib.sha256(data).hexdigest()


def pinned_file(root, record):
    path = (root / record['path']).resolve()
    data = path.read_bytes()
    if digest(data) != record['sha256']:
        raise ValueError('Extension input hash mismatch: ' + str(path))
    return path, data


def apply_extensions(image, reference, config, manifest_path, compile_source=None):
    """Validate inputs first, then replace complete source modules and fragments.

    compile_source receives an existing module descriptor with an explicitly
    selected external source path. It must use the normal compiler, check linked
    entries, and return generated bytes. This API grants no recovery credit.
    """
    manifest_path = Path(manifest_path).resolve()
    root = manifest_path.parent
    manifest = json.loads(manifest_path.read_text())
    if manifest.get('schema') != 'build-extension-v1':
        raise ValueError('Unsupported extension schema')
    if manifest.get('reference_sha256') != digest(reference) or len(image) != len(reference):
        raise ValueError('Extension reference identity or image size mismatch')
    sources = manifest.get('sources', [])
    if not sources:
        raise ValueError('Extension requires pinned source provenance')
    for record in sources:
        pinned_file(root, record)
    modules = {module['name']: module for module in config['modules']}
    planned = []
    occupied = []

    def reserve(offset, size, expected):
        if type(offset) is not int or type(size) is not int or size <= 0 or offset < 0 or offset + size > len(image):
            raise ValueError('Extension range outside ROM')
        if digest(reference[offset:offset + size]) != expected:
            raise ValueError('Extension original range hash mismatch')
        occupied.append((offset, offset + size))

    seen = set()
    for replacement in manifest.get('source_replacements', []):
        name = replacement['module']
        if name in seen or name not in modules:
            raise ValueError('Duplicate or unknown extension module: ' + name)
        seen.add(name)
        module = copy.deepcopy(modules[name])
        if module['kind'] not in ('c', 'mixed', 'assembly') or not module.get('enabled', True):
            raise ValueError('Extension replacement requires an enabled source module')
        path, data = pinned_file(root, replacement['source'])
        module['source'] = str(path)
        fill = replacement.get('fill_byte', 0)
        if type(fill) is not int or not 0 <= fill <= 255:
            raise ValueError('Invalid extension padding byte')
        reserve(module['offset'], module['size'], replacement['reference_sha256'])
        planned.append(('source', module, fill, replacement['source']['sha256']))
    fragments = []
    for fragment in manifest.get('fragments', []):
        path, data = pinned_file(root, fragment)
        if fragment.get('kind') not in ('resource', 'data', 'code'):
            raise ValueError('Extension fragment requires an explicit classification')
        reserve(fragment['rom_offset'], len(data), fragment['reference_sha256'])
        fragments.append((fragment['rom_offset'], data, fragment['kind']))
    # Byte-identical resource overlaps are permitted. Source replacement spans
    # are exclusive because their output is not available until compilation.
    source_spans = occupied[:len(planned)]
    for i, (begin, end) in enumerate(source_spans):
        if any(begin < other_end and other_begin < end
               for other_begin, other_end in occupied[i + 1:]):
            raise ValueError('Overlapping source extension ranges')
        if any(begin < other_end and other_begin < end
               for other_begin, other_end in source_spans[:i]):
            raise ValueError('Overlapping source extension ranges')
    output = bytearray(image)
    written = {}
    for offset, data, kind in fragments:
        for index, value in enumerate(data, offset):
            if index in written and written[index] != value:
                raise ValueError('Conflicting extension fragments')
            written[index] = value
        output[offset:offset + len(data)] = data
    reports = []
    for _, module, fill, source_sha in planned:
        if compile_source is None:
            raise ValueError('Source extension compiler is unavailable')
        data = compile_source(module)
        if not data or len(data) > module['size']:
            raise ValueError('Extension source exceeds original module envelope: ' + module['name'])
        offset = module['offset']
        output[offset:offset + module['size']] = data + bytes([fill]) * (module['size'] - len(data))
        reports.append({'module': module['name'], 'source_sha256': source_sha,
                        'generated_bytes': len(data), 'envelope_bytes': module['size'],
                        'generated_sha256': digest(data)})
    return bytes(output), {'manifest_sha256': digest(manifest_path.read_bytes()),
                          'source_replacements': reports, 'fragment_count': len(fragments),
                          'output_sha256': digest(output), 'recovery_credit_eligible': False}
